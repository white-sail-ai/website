/** The company's own mark, in the station's single ink; nothing when the company has none here. */
export function CompanyMark({ company, className }: GlyphProps & { company: string }) {
  const mark = COMPANY_MARKS[company];
  if (!mark) return null;
  return (
    <svg
      className={className}
      viewBox={mark.viewBox}
      style={{ "--mark-w": mark.width } as CSSProperties}
      aria-hidden="true"
    >
      {mark.paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}

